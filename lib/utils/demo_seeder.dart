  static List<Sale> getDemoSales() {
    final now = DateTime.now();
    final meds = getDemoMedicines();
    final sales = <Sale>[];

    for (int day = 0; day < 30; day++) {
      final saleDate = now.subtract(Duration(days: day, hours: 2));
      final med = meds[day % meds.length];
      final qty = (day % 3) + 1;
      final subtotal = med.price * qty;
      final isPakka = day % 2 == 0;
      final tax = isPakka ? subtotal * (med.gstSlab / 100.0) : 0.0;
      final total = subtotal + tax;

      sales.add(Sale(
        id: 'demo_sale_$day',
        billNo: 'PH-2026-${(1000 + day)}',
        customerName: 'Customer ${day + 1}',
        medicineId: med.id,
        medicineName: med.name,
        quantity: qty,
        unitPrice: med.price,
        subtotal: subtotal,
        taxAmount: tax,
        totalPrice: total,
        billType: isPakka ? 'pakka' : 'kaccha',
        date: saleDate,
        items: [
          SaleItem(
            medicineId: med.id,
            medicineName: med.name,
            quantity: qty,
            unitPrice: med.price,
            totalPrice: subtotal,
            hsn: med.hsn,
            gstSlab: med.gstSlab,
            taxAmount: tax,
          ),
        ],
      ));
    }

    return sales;
  }
